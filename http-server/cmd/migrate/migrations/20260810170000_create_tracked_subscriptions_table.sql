CREATE TABLE IF NOT EXISTS tracked_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT (timezone('UTC', now())),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT (timezone('UTC', now())),

    user_uuid VARCHAR(255) NOT NULL REFERENCES user_cores(user_uuid) ON DELETE CASCADE,

    name TEXT NOT NULL,
    price NUMERIC(10, 3) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'USD',
    period VARCHAR(10) NOT NULL DEFAULT 'monthly',
    date_pay DATE NOT NULL,

    auto_renewal BOOLEAN NOT NULL DEFAULT TRUE,
    notification BOOLEAN NOT NULL DEFAULT FALSE,
    include_in_analytics BOOLEAN NOT NULL DEFAULT TRUE,
    note TEXT,

    CONSTRAINT chk_tracked_subscriptions_period CHECK (period IN ('monthly', 'yearly')),
    CONSTRAINT chk_tracked_subscriptions_currency CHECK (currency ~ '^[A-Z]{3}$')
);

CREATE INDEX IF NOT EXISTS idx_tracked_subscriptions_user_uuid ON tracked_subscriptions(user_uuid);
CREATE INDEX IF NOT EXISTS idx_tracked_subscriptions_date_pay ON tracked_subscriptions(date_pay);
CREATE INDEX IF NOT EXISTS idx_tracked_subscriptions_analytics ON tracked_subscriptions(user_uuid, include_in_analytics);

CREATE TABLE IF NOT EXISTS subscription_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT (timezone('UTC', now())),
    slug VARCHAR(64) NOT NULL,

    CONSTRAINT uq_subscription_categories_slug UNIQUE (slug)
);

CREATE TABLE IF NOT EXISTS tracked_subscription_categories (
    tracked_subscription_id BIGINT NOT NULL REFERENCES tracked_subscriptions(id) ON DELETE CASCADE,
    user_uuid VARCHAR(255) NOT NULL REFERENCES user_cores(user_uuid) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES subscription_categories(id) ON DELETE CASCADE,

    PRIMARY KEY (tracked_subscription_id, user_uuid, category_id)
);

CREATE INDEX IF NOT EXISTS idx_tracked_subscription_categories_category_id ON tracked_subscription_categories(category_id);
CREATE INDEX IF NOT EXISTS idx_tracked_subscription_categories_user_uuid ON tracked_subscription_categories(user_uuid);

