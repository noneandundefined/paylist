CREATE OR REPLACE FUNCTION set_tracked_sub_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('UTC', now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_tracked_sub_updated_at_trigger ON tracked_subscriptions;
CREATE TRIGGER set_tracked_sub_updated_at_trigger
    BEFORE UPDATE ON tracked_subscriptions
    FOR EACH ROW
    EXECUTE FUNCTION set_tracked_sub_updated_at();

